// 金額在引擎裡的單位是「萬元」
function fmt(v) {
  const a = Math.abs(v);
  const s = v < 0 ? '−' : '';
  if (a >= 10000) return s + (a / 10000).toFixed(2) + ' 億';
  if (a >= 100) return s + Math.round(a).toLocaleString() + ' 萬';
  return s + (Math.round(a * 10) / 10) + ' 萬';
}

