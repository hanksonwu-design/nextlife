// 出現最多次的類型;同票時取先出現的
function mode(answers) {
  const count = {};
  let best = answers[0];
  for (const k of answers) {
    count[k] = (count[k] || 0) + 1;
    if (count[k] > count[best]) best = k;
  }
  return best;
}
